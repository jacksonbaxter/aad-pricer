#!/usr/bin/env python3
"""Exact values of the standard normal CDF for tests/pricer/normal_cdf_test.cpp.

    python3 -I tests/pricer/normal_cdf_reference.py --write | --check

Writes tests/pricer/normal_cdf_values.inc: for each input x, y = -x / sqrt 2 rounded to double as
the C++ code rounds it (Python's float division and math.sqrt are correctly rounded, so this is
the same double), and erfc(y) / 2 in decimal arithmetic as hi + lo, hi the nearest double. So the
table measures the erfc kernel on the argument it really gets. It also stores Phi(x) itself, the
exact value at the unrounded x, so the test can report what the rounding of y adds.

Standard library only. erfc comes from tools/math_reference/generate.py, by series below 2.5 and
by continued fraction above, both in decimal arithmetic; nothing calls the host's libm for a value
written to the table. Self-checks first: series and fraction agree where both converge, and the
fraction is stable at twice its depth.

--check regenerates the table and exits 1 if it differs from the committed file by a byte.
Exit codes: 0 pass, 1 self-check failed or --check found a difference, 2 usage.
"""

import decimal
import math
import os
import random
import sys
from decimal import Decimal as D

HERE = os.path.dirname(os.path.realpath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.dont_write_bytecode = True  # importing must leave no __pycache__ in the source tree
sys.path.insert(0, os.path.join(REPO, "tools", "math_reference"))
import generate  # noqa: E402  (the shared decimal erfc, not a copy of it)

TABLE = os.path.join(HERE, "normal_cdf_values.inc")
PREC = 40  # digits. The table needs about 35; the series below 2.5 cancels about 4.
# Development seed for the random points. Never 1729 or 271828, which are reserved.
SEED = 20261104
SMALL_BOUND = 0.46875
MIDDLE_BOUND = 4.0
SMALLEST_NORMAL = 2.0**-1022


def setup():
    """pi at the generator's own precision, which its published-digits check needs, then ours."""
    decimal.setcontext(generate.context())
    sqrt_pi = generate.compute_pi().sqrt()
    generate.PREC = PREC
    decimal.setcontext(generate.context())
    return +sqrt_pi


def erfc(z, sqrt_pi):
    if z == 0:
        return D(1)  # the shared series never terminates on an all-zero sum
    if z > 0:
        return generate.erfc(z, sqrt_pi)
    return 2 - generate.erfc(-z, sqrt_pi)


def self_check(sqrt_pi):
    for z in (D("2.5"), D("3"), D("4.5")):
        series = 1 - generate.erf_series(z, sqrt_pi)
        fraction = generate.erfc_fraction(z, sqrt_pi, generate.fraction_depth(z))
        # 1 - erf cancels, so the series is good to about 10^-PREC absolute, not relative.
        if abs(series - fraction) > D(10) ** -(PREC - 3):
            raise SystemExit(f"self-check: erfc({z}) by series and by fraction disagree")
    for z in (D("2.5"), D("7"), D("27.5")):
        once = generate.erfc_fraction(z, sqrt_pi, generate.fraction_depth(z))
        twice = generate.erfc_fraction(z, sqrt_pi, 2 * generate.fraction_depth(z))
        if abs(once - twice) > once * D(10) ** -(PREC - 3):
            raise SystemExit(f"self-check: erfc({z}) fraction depth")


def inputs():
    rng = random.Random(SEED)
    xs = [i / 8.0 for i in range(-308, 73)]  # -38.5 to 9
    xs += [rng.uniform(-38.5, 9.0) for _ in range(400)]
    xs += [rng.uniform(-3.0, 3.0) for _ in range(200)]
    # Each side of the region joins, in y = -x / sqrt 2.
    for bound in (SMALL_BOUND, MIDDLE_BOUND):
        for sign in (1.0, -1.0):
            x = -sign * bound * math.sqrt(2.0)
            for _ in range(3):
                xs += [x]
                x = math.nextafter(x, math.inf)
            x = -sign * bound * math.sqrt(2.0)
            for _ in range(3):
                x = math.nextafter(x, -math.inf)
                xs += [x]
    xs += [0.0, 1e-300, -1e-300, -37.5, -38.0, -38.4]
    return sorted(set(xs))


def domain(y, value):
    a = abs(y)
    if a <= SMALL_BOUND:
        return 0
    if a <= MIDDLE_BOUND:
        return 1
    return 2 if value >= SMALLEST_NORMAL else 3


def render(sqrt_pi):
    sqrt2 = D(2).sqrt()
    rows = []
    for x in inputs():
        y = -x / math.sqrt(2.0)
        exact = erfc(D(y), sqrt_pi) / 2
        hi, lo = generate.split(exact)
        phi_hi, phi_lo = generate.split(erfc(-D(x) / sqrt2, sqrt_pi) / 2)
        rows.append(
            f"    {{{x.hex()}, {y.hex()}, {hi.hex()}, {lo.hex()}, {phi_hi.hex()}, "
            f"{phi_lo.hex()}, {domain(y, hi)}}},\n")
    return (
        "// clang-format off\n"
        "// Generated by tests/pricer/normal_cdf_reference.py. Do not edit.\n"
        "// {x, y = -x / sqrt 2 rounded, erfc(y) / 2 as hi + lo, Phi(x) as hi + lo, domain}\n"
        f"inline constexpr std::array<NormalCdfPoint, {len(rows)}> kNormalCdfReference = {{{{\n"
        + "".join(rows) + "}};\n// clang-format on\n")


def main(argv):
    if len(argv) != 2 or argv[1] not in ("--write", "--check"):
        print(__doc__.strip().splitlines()[2].strip(), file=sys.stderr)
        return 2
    sqrt_pi = setup()
    self_check(sqrt_pi)
    text = render(sqrt_pi)
    if argv[1] == "--write":
        with open(TABLE, "w", encoding="utf-8") as out:
            out.write(text)
        return 0
    try:
        with open(TABLE, encoding="utf-8") as current:
            committed = current.read()
    except OSError as error:
        print(f"normal_cdf_reference: cannot read {TABLE}: {error}", file=sys.stderr)
        return 1
    if committed != text:
        print(f"normal_cdf_reference: {TABLE} differs from what the script generates",
              file=sys.stderr)
        return 1
    print("normal_cdf_reference: table current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
