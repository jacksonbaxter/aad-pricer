// The readers behind RESULTS.md and the README's headline (results/docs.hpp). Properties, beyond
// not crashing: a measured run's counts agree with its rows, splicing the same block twice
// changes nothing, and two texts differ exactly when a difference line is found.
#include <cstddef>
#include <cstdint>
#include <string>
#include <string_view>

#include "results/docs.hpp"

#define FUZZ_ASSERT(condition) \
  do {                         \
    if (!(condition)) {        \
      __builtin_trap();        \
    }                          \
  } while (false)

extern "C" int LLVMFuzzerTestOneInput(const std::uint8_t* data, std::size_t size) {
  const std::string_view text(reinterpret_cast<const char*>(data), size);
  namespace r = aadp::results;

  if (const auto run = r::parse_measured_run(text)) {
    FUZZ_ASSERT(!run->rows.empty() && run->passed <= run->rows.size());
  }
  if (const auto report = r::parse_fault_report(text)) {
    FUZZ_ASSERT(report->header.contains("host_label"));
  }
  (void)r::target_heading(text, "AAD-1");

  // The input as a README. A block with no marker in it splices the same way twice; the input
  // itself as the block may hold markers, so only its length is checked.
  constexpr std::string_view kBlock = "| a | b |\n";
  if (const auto once = r::splice_headline(text, kBlock)) {
    const auto twice = r::splice_headline(*once, kBlock);
    FUZZ_ASSERT(twice.has_value() && *twice == *once);
  }
  const auto self = r::splice_headline(text, text);
  FUZZ_ASSERT(!self || self->size() >= text.size());
  const std::string copy = std::string(text) + "x";
  FUZZ_ASSERT(r::first_difference_line(text, text) == 0);
  FUZZ_ASSERT(r::first_difference_line(text, copy) != 0);

  // The input as the spec, as BENCHMARKS.md and as every run it names, with no results files.
  if (const auto spec = r::parse_headline_spec(text)) {
    r::DocsInputs inputs;
    inputs.spec = std::string(text);
    inputs.benchmarks = std::string(text);
    for (const r::HeadlineRow& row : spec->measured_runs) {
      inputs.measured_runs[row.source] = std::string(text);
    }
    const auto docs = r::render_docs(inputs);
    FUZZ_ASSERT(!docs || docs->results_md.starts_with("<!-- Generated by"));
  }
  return 0;
}
