# Normal distribution in high precision

def erf_series(z, sqrt_pi):
    """erf(z) = 2/sqrt(pi) exp(-z^2) sum 2^n z^(2n+1) / (2n+1)!!, every term positive."""
    term = z
    total = z
    n = 0
    z2 = z * z
    while True:
        term = term * 2 * z2 / (2 * n + 3)
        n += 1
        if term < total * D(10) ** -(PREC + 3):
            break
        total += term
    return 2 / sqrt_pi * (-z2).exp() * total


def erfc_fraction(z, sqrt_pi, depth):
    """erfc(z) = exp(-z^2)/sqrt(pi) / (z + (1/2)/(z + 1/(z + (3/2)/(z + ...)))), z > 0."""
    t = z
    for n in range(depth, 0, -1):
        t = z + D(n) / 2 / t
    return (-z * z).exp() / sqrt_pi / t


def fraction_depth(z):
    """Terms for about PREC digits. Convergence goes like exp(-2 sqrt(2 n) z)."""
    digits = PREC + 5
    n = (digits * D(10).ln() / (2 * D(2).sqrt() * z)) ** 2
    return int(n) + 60


SERIES_LIMIT = D("2.5")


def erfc(z, sqrt_pi):
    """For z >= 0."""
    if z < SERIES_LIMIT:
        return 1 - erf_series(z, sqrt_pi)
    return erfc_fraction(z, sqrt_pi, fraction_depth(z))


def check_erfc(sqrt_pi):
    for z in (D("2.5"), D("3"), D("4.5")):
        series = 1 - erf_series(z, sqrt_pi)
        fraction = erfc_fraction(z, sqrt_pi, fraction_depth(z))
        check(abs(series - fraction) <= fraction * D("1e-55"), f"erfc({z}): series and fraction")
    for z in (D("2.5"), D("7"), D("27.5")):
        once = erfc_fraction(z, sqrt_pi, fraction_depth(z))
        twice = erfc_fraction(z, sqrt_pi, 2 * fraction_depth(z))
        check(abs(once - twice) <= once * D("1e-60"), f"erfc({z}): fraction depth")


def lower_residual(x, tail, sqrt_pi, sqrt2):
    """Phi(x) - tail for x <= 0. Near the centre as (1/2 - tail) - erf(z)/2, where 1/2 - tail is
    exact, so the residual keeps its relative precision as x goes to 0."""
    z = -x / sqrt2
    if z < SERIES_LIMIT:
        return (D("0.5") - tail) - erf_series(z, sqrt_pi) / 2
    return erfc_fraction(z, sqrt_pi, fraction_depth(z)) / 2 - tail


def as241_start(tail):
    """AS241 PPND16 in decimal arithmetic, lower tail, as a start for Newton. Coefficients from
    Wichura (1988), the same as src/rng/normal.hpp."""
    a = ["3.3871328727963666080e0", "1.3314166789178437745e+2", "1.9715909503065514427e+3",
         "1.3731693765509461125e+4", "4.5921953931549871457e+4", "6.7265770927008700853e+4",
         "3.3430575583588128105e+4", "2.5090809287301226727e+3"]
    b = ["1.0", "4.2313330701600911252e+1", "6.8718700749205790830e+2",
         "5.3941960214247511077e+3", "2.1213794301586595867e+4", "3.9307895800092710610e+4",
         "2.8729085735721942674e+4", "5.2264952788528545610e+3"]
    c = ["1.42343711074968357734e0", "4.63033784615654529590e0", "5.76949722146069140550e0",
         "3.64784832476320460504e0", "1.27045825245236838258e0", "2.41780725177450611770e-1",
         "2.27238449892691845833e-2", "7.74545014278341407640e-4"]
    d = ["1.0", "2.05319162663775882187e0", "1.67638483018380384940e0",
         "6.89767334985100004550e-1", "1.48103976427480074590e-1", "1.51986665636164571966e-2",
         "5.47593808499534494600e-4", "1.05075007164441684324e-9"]
    e = ["6.65790464350110377720e0", "5.46378491116411436990e0", "1.78482653991729133580e0",
         "2.96560571828504891230e-1", "2.65321895265761230930e-2", "1.24266094738807843860e-3",
         "2.71155556874348757815e-5", "2.01033439929228813265e-7"]
    f = ["1.0", "5.99832206555887937690e-1", "1.36929880922735805310e-1",
         "1.48753612908506148525e-2", "7.86869131145613259100e-4", "1.84631831751005468180e-5",
         "1.42151175831644588870e-7", "2.04426310338993978564e-15"]

    def poly(coefficients, t):
        return horner([D(s) for s in coefficients], t)

    q = tail - D("0.5")
    if abs(q) <= D("0.425"):
        r = D("0.180625") - q * q
        return q * poly(a, r) / poly(b, r)
    r = (-tail.ln()).sqrt()
    if r <= 5:
        r -= D("1.6")
        return -poly(c, r) / poly(d, r)
    r -= 5
    return -poly(e, r) / poly(f, r)


def inverse_lower(tail, sqrt_pi, sqrt2):
    """x <= 0 with Phi(x) = tail, 0 < tail <= 1/2, by Newton from the AS241 start."""
    if tail == D("0.5"):
        return D(0)
    x = as241_start(tail)
    norm = 1 / (sqrt2 * sqrt_pi)
    for _ in range(8):
        pdf = norm * (-x * x / 2).exp()
        step = lower_residual(x, tail, sqrt_pi, sqrt2) / pdf
        x -= step
        if abs(step) <= abs(x) * D(10) ** -(PREC - 15):
            return x
    raise SelfCheckError(f"inverse normal: Newton did not converge at {tail}")


