# Conversions

def to_double(value):
    """Nearest double, ties to even. Infinite beyond the overflow threshold, as IEEE rounds."""
    return float(value)


def split(value):
    """value as hi + lo: hi the nearest double, lo the nearest double to the remainder."""
    hi = to_double(value)
    if hi in (float("inf"), float("-inf")):
        return hi, 0.0
    return hi, to_double(value - D(hi))


def hex_literal(x):
    if x == float("inf"):
        return "kInf"
    if x == float("-inf"):
        return "-kInf"
    return x.hex()


def uniform(rng):
    """A uniform Decimal in [0, 1) with 53 random bits, from Python's Mersenne Twister."""
    return D(rng.getrandbits(53)) / D(2**53)


def ulp_neighbours(x, count):
    """x and up to count doubles on each side of it, by stepping the bit pattern."""
    out = []
    for step in range(-count, count + 1):
        y = step_ulps(x, step)
        if y is not None:
            out.append(y)
    return out


def step_ulps(x, steps):
    """The double steps ulps from x, for finite positive or negative x, or None at the edges."""
    (bits,) = struct.unpack("<q", struct.pack("<d", x))
    if x < 0:
        bits = -(bits & 0x7FFFFFFFFFFFFFFF)
    bits += steps
    if bits < 0:
        if -bits >= 0x7FF0000000000000:
            return None
        bits = (-bits) | (1 << 63)
    elif bits >= 0x7FF0000000000000:
        return None
    (y,) = struct.unpack("<d", struct.pack("<Q", bits & 0xFFFFFFFFFFFFFFFF))
    return y


