# Remez exchange for a relative-error minimax polynomial

def horner(coefficients, t):
    total = D(0)
    for c in reversed(coefficients):
        total = total * t + c
    return total


def solve(matrix, rhs):
    """Gaussian elimination with partial pivoting."""
    n = len(rhs)
    a = [row[:] + [rhs[i]] for i, row in enumerate(matrix)]
    for col in range(n):
        pivot = max(range(col, n), key=lambda r: abs(a[r][col]))
        check(a[pivot][col] != 0, "Remez: singular reference system")
        a[col], a[pivot] = a[pivot], a[col]
        for r in range(col + 1, n):
            factor = a[r][col] / a[col][col]
            for c in range(col, n + 1):
                a[r][c] -= factor * a[col][c]
    x = [D(0)] * n
    for r in range(n - 1, -1, -1):
        x[r] = (a[r][n] - sum(a[r][c] * x[c] for c in range(r + 1, n))) / a[r][r]
    return x


def alternating_extrema(grid, errors, count):
    """One extremum per run of constant sign, then trimmed at the ends to count points."""
    runs = []
    start = 0
    for i in range(1, len(grid) + 1):
        if i == len(grid) or (errors[i] > 0) != (errors[start] > 0):
            best = max(range(start, i), key=lambda j: abs(errors[j]))
            runs.append(best)
            start = i
    check(len(runs) >= count, f"Remez: {len(runs)} alternations, need {count}")
    while len(runs) > count:
        if abs(errors[runs[0]]) < abs(errors[runs[-1]]):
            runs.pop(0)
        else:
            runs.pop()
    return runs


def remez(name, g, lo, hi, degree, pi, grid_size=6000):
    """Minimax polynomial of the given degree for g on [lo, hi], in relative error."""
    n = degree
    reference = [(lo + hi) / 2 - (hi - lo) / 2 * cos_series(pi * i / (n + 1)) for i in range(n + 2)]
    grid = [lo + (hi - lo) * D(j) / D(grid_size) for j in range(grid_size + 1)]
    values = [g(t) for t in grid]
    for _ in range(40):
        matrix = []
        rhs = []
        for i, t in enumerate(reference):
            gt = g(t)
            powers = [D(1)]
            for _ in range(n):
                powers.append(powers[-1] * t)
            matrix.append(powers + [(-1) ** i * gt])
            rhs.append(gt)
        solution = solve(matrix, rhs)
        coefficients, levelled = solution[: n + 1], abs(solution[n + 1])
        errors = [(horner(coefficients, t) - v) / v for t, v in zip(grid, values)]
        worst = max(abs(e) for e in errors)
        if worst <= levelled * D("1.0001"):
            return coefficients, levelled
        reference = [grid[j] for j in alternating_extrema(grid, errors, n + 2)]
    raise SelfCheckError(f"Remez {name}: did not level in 40 exchanges")


def rounded_fit_error(coefficients, g, lo, hi, points=20000):
    """Max relative error of the polynomial with its coefficients rounded to double."""
    rounded = [D(to_double(c)) for c in coefficients]
    worst = D(0)
    for j in range(points + 1):
        t = lo + (hi - lo) * D(j) / D(points)
        v = g(t)
        worst = max(worst, abs((horner(rounded, t) - v) / v))
    return worst


# exp(r) = 1 + r + r^2 q(r). The kernel's |r| reaches ln2/2 plus a few ulps of the reduction.
EXP_R_MAX = D("0.34658")
EXP_DEGREE = 10
# The fit enters exp as r^2 q (P - q) / q relative to the result, at most 0.076 times the relative
# fit error, at r = -ln2/2. An ULP is at least 2^-53 of the result, so this limit keeps the fit's
# share of the error below 0.01 ULP.
EXP_FIT_LIMIT = D("0.01") * D(2) ** -53 / D("0.076")


def exp_q(r):
    """(exp(r) - 1 - r) / r^2 = sum r^n / (n + 2)!, summed directly so r = 0 is no problem."""
    term = D(1) / 2
    total = term
    n = 0
    while True:
        term = term * r / (n + 3)
        if abs(term) < D(10) ** -(PREC + 5):
            return total
        total += term
        n += 1


# log(1 + f) = f - f^2/2 + s (f^2/2 + z g(z)), s = f / (2 + f), z = s^2. g(z) = (2 atanh(s) / s - 2)
# / z = sum 2 z^(k-1) / (2k + 1). s reaches (sqrt 2 - 1) / (sqrt 2 + 1), so z reaches 0.0294373.
LOG_Z_MAX = D("0.02944")
LOG_DEGREE = 7
# The fit enters log as s z (P - g), at most 0.0099 times the relative fit error, relative to the
# result, at the ends of the interval. As for exp, the limit keeps that below 0.01 ULP.
LOG_FIT_LIMIT = D("0.01") * D(2) ** -53 / D("0.0099")


def log_g(z):
    total = D(0)
    power = D(1)
    k = 1
    while True:
        term = 2 * power / (2 * k + 1)
        if term < D(10) ** -(PREC + 5):
            return total
        total += term
        power *= z
        k += 1


def fits(pi):
    exp_coefficients, exp_level = remez("exp", exp_q, -EXP_R_MAX, EXP_R_MAX, EXP_DEGREE, pi)
    exp_error = rounded_fit_error(exp_coefficients, exp_q, -EXP_R_MAX, EXP_R_MAX)
    check(exp_error <= EXP_FIT_LIMIT, f"exp fit: rounded error {exp_error:.3e} > limit")
    log_coefficients, log_level = remez("log", log_g, D(0), LOG_Z_MAX, LOG_DEGREE, pi)
    log_error = rounded_fit_error(log_coefficients, log_g, D(0), LOG_Z_MAX)
    check(log_error <= LOG_FIT_LIMIT, f"log fit: rounded error {log_error:.3e} > limit")
    return {
        "exp": (exp_coefficients, exp_level, exp_error),
        "log": (log_coefficients, log_level, log_error),
    }


def coefficient_block(name, coefficients, level, error, variable, lo, hi):
    lines = [
        BEGIN_MARK,
        f"// Remez minimax in relative error, degree {len(coefficients) - 1} in {variable} on"
        f" [{lo}, {hi}].\n",
        f"// Levelled error {float(level):.3e}; with the coefficients rounded to double,"
        f" {float(error):.3e}.\n",
        f"inline constexpr std::array<double, {len(coefficients)}> {name} = {{\n",
    ]
    for c in coefficients:
        lines.append(f"    {to_double(c).hex()},  // {to_double(c)!r}\n")
    lines.append("};\n")
    lines.append(END_MARK)
    return "".join(lines)


