# Constants

def arctan_inverse(n):
    """atan(1/n) for an integer n > 1, by its Taylor series."""
    x = D(1) / n
    x2 = x * x
    term = x
    total = x
    k = 1
    while True:
        term = -term * x2
        add = term / (2 * k + 1)
        if add == 0 or abs(add) < D(10) ** -(PREC + 5):
            break
        total += add
        k += 1
    return total


def compute_pi():
    """Machin's formula, checked against a published 60-digit value."""
    pi = 16 * arctan_inverse(5) - 4 * arctan_inverse(239)
    published = D("3.14159265358979323846264338327950288419716939937510582097494")
    check(abs(pi - published) < D("1e-58"), "pi: Machin's formula disagrees with the literal")
    return pi


def cos_series(x):
    term = D(1)
    total = D(1)
    k = 0
    while True:
        term = -term * x * x / ((2 * k + 1) * (2 * k + 2))
        if abs(term) < D(10) ** -(PREC + 5):
            break
        total += term
        k += 1
    return total


