def render_table(pi):
    rng = random.Random(SEED)
    ln2 = D(2).ln()
    sqrt2 = D(2).sqrt()
    sqrt_pi = pi.sqrt()
    out = [
        "// Generated by tools/math_reference/generate.py. Do not edit: --check regenerates it.\n",
        "// Each entry: input, then the exact result as hi + lo, hi the nearest double, then the\n",
        "// index of its domain in the names array.\n",
    ]

    # ln2 as three doubles, each the nearest to what is left, for the double-double reference.
    parts = []
    left = ln2
    for _ in range(3):
        parts.append(to_double(left))
        left -= D(parts[-1])
    check(abs(left) < D(2) ** -150, "ln2 triple: not 2^-150 accurate")
    out.append("// ln2 as three doubles, each the nearest to what the earlier ones leave.\n")
    out.append("inline constexpr std::array<double, 3> kLn2Triple = {"
               + ", ".join(x.hex() for x in parts) + "};\n")

    def block(name, domains, entries):
        out.append(f"inline constexpr std::array<const char*, {len(domains)}> {name}Domains = {{\n")
        for d in domains:
            out.append(f'    "{d}",\n')
        out.append("};\n")
        out.append(f"inline constexpr std::array<ReferencePoint, {len(entries)}> {name} = {{{{\n")
        for x, hi, lo, domain in entries:
            out.append(f"    {{{hex_literal(x)}, {hex_literal(hi)}, {hex_literal(lo)}, {domain}}},\n")
        out.append("}};\n")

    entries = []
    for x, domain in exp_inputs(rng, ln2):
        hi, lo = split(D(x).exp())
        entries.append((x, hi, lo, domain))
    block("kExpReference", EXP_DOMAINS, entries)

    entries = []
    for x, domain in log_inputs(rng, sqrt2):
        hi, lo = split(D(x).ln())
        entries.append((x, hi, lo, domain))
    block("kLogReference", LOG_DOMAINS, entries)

    entries = []
    for p, domain in inverse_normal_inputs(rng):
        dp = D(p)
        if dp <= D("0.5"):
            value = inverse_lower(dp, sqrt_pi, sqrt2)
        else:
            value = -inverse_lower(1 - dp, sqrt_pi, sqrt2)
        hi, lo = split(value)
        entries.append((p, hi, lo, domain))
    block("kInverseNormalReference", INVERSE_NORMAL_DOMAINS, entries)
    return "".join(out)


def replace_block(text, block, path):
    begin = text.find(BEGIN_MARK)
    end = text.find(END_MARK)
    if begin < 0 or end < begin or text.count(BEGIN_MARK) != 1:
        raise SelfCheckError(f"{path}: needs exactly one generated block")
    return text[:begin] + block + text[end + len(END_MARK):]


def constants_block():
    ln2 = D(2).ln()
    scaled = ln2 * D(2) ** 42
    hi_bits = int(scaled.to_integral_value(rounding=decimal.ROUND_HALF_EVEN))
    ln2_hi = float(Fraction(hi_bits, 2**42))
    ln2_lo = to_double(ln2 - D(ln2_hi))
    check(abs(ln2 - D(ln2_hi) - D(ln2_lo)) < D(2) ** -95, "ln2 split: not 2^-95 accurate")
    check(hi_bits.bit_length() <= 42, "ln2 split: kLn2Hi has more than 42 bits")
    sqrt2 = to_double(D(2).sqrt())
    check(D(sqrt2) > D(2).sqrt(), "sqrt 2 rounds down, so m = sqrt 2 would be possible")
    lines = [
        BEGIN_MARK,
        f"// ln2 to 42 bits, so k * kLn2Hi is exact for |k| < 2^11: {ln2_hi!r}\n",
        "// NOLINTNEXTLINE(modernize-use-std-numbers): a 42-bit split of ln2, not ln2 itself.\n",
        f"inline constexpr double kLn2Hi = {ln2_hi.hex()};\n",
        f"// ln2 - kLn2Hi, rounded: the pair is good to 2^-95: {ln2_lo!r}\n",
        f"inline constexpr double kLn2Lo = {ln2_lo.hex()};\n",
        "// 1 / ln2 and sqrt 2, rounded to nearest. The asserts tie std::numbers to this script.\n",
        "// kSqrt2 rounds up, so a mantissa below it is below sqrt 2.\n",
        "inline constexpr double kInvLn2 = std::numbers::log2e;\n",
        "// NOLINTNEXTLINE(modernize-use-std-numbers): the literal is the point of the check.\n",
        f"static_assert(kInvLn2 == {to_double(1 / ln2).hex()});\n",
        "inline constexpr double kSqrt2 = std::numbers::sqrt2;\n",
        "// NOLINTNEXTLINE(modernize-use-std-numbers): the literal is the point of the check.\n",
        f"static_assert(kSqrt2 == {sqrt2.hex()});\n",
    ]
    lines.append(END_MARK)
    return "".join(lines)


def outputs():
    with decimal.localcontext(context()):
        pi = compute_pi()
        check_erfc(pi.sqrt())
        fitted = fits(pi)
        exp_block = coefficient_block("kExpPoly", *fitted["exp"], "r", -EXP_R_MAX, EXP_R_MAX)
        log_block = coefficient_block("kLogPoly", *fitted["log"], "z", D(0), LOG_Z_MAX)
        common_block = constants_block()
        table = render_table(pi)
    result = {TABLE_PATH: table}
    for path, block in ((COMMON_HEADER, common_block), (EXP_HEADER, exp_block),
                        (LOG_HEADER, log_block)):
        with open(os.path.join(REPO, path), encoding="utf-8") as handle:
            result[path] = replace_block(handle.read(), block, path)
    return result


def survey(count, path):
    """count random p in each region, with exact inverse normal values, one line each:
    p hi lo domain, in hex. Not committed: for tools/math_reference/survey.cpp."""
    rng = random.Random(SEED + 1)
    lines = []
    with decimal.localcontext(context()):
        sqrt_pi = compute_pi().sqrt()
        sqrt2 = D(2).sqrt()
        for domain in range(3):
            for _ in range(count):
                upper = rng.getrandbits(1) == 1
                if domain == 0:
                    p = to_double(D("0.075") + D("0.85") * uniform(rng))
                else:
                    # Log-uniform in the tail. The far tail reaches 2^-1074 below 1/2 and only
                    # 2^-53 above it, where 1 - p is the tail.
                    if domain == 1:
                        low, high = D(-25), D("0.075").ln()
                    else:
                        low, high = (D(2) ** (-53 if upper else -1074)).ln(), D(-25)
                    tail = (low + (high - low) * uniform(rng)).exp()
                    p = to_double(1 - tail) if upper else to_double(tail)
                dp = D(p)
                if dp <= D("0.5"):
                    value = inverse_lower(dp, sqrt_pi, sqrt2)
                else:
                    value = -inverse_lower(1 - dp, sqrt_pi, sqrt2)
                hi, lo = split(value)
                lines.append(f"{p.hex()} {hi.hex()} {lo.hex()} {domain}\n")
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("".join(lines))
    return 0


def main(argv):
    if len(argv) == 4 and argv[1] == "--survey" and argv[2].isdigit():
        try:
            return survey(int(argv[2]), argv[3])
        except SelfCheckError as error:
            print(f"generate: self-check failed: {error}", file=sys.stderr)
            return 1
    if len(argv) != 2 or argv[1] not in ("--write", "--check"):
        print("usage: generate.py --write | --check | --survey <count> <file>", file=sys.stderr)
        return 2
    try:
        generated = outputs()
    except SelfCheckError as error:
        print(f"generate: self-check failed: {error}", file=sys.stderr)
        return 1
    status = 0
    for path, text in generated.items():
        full = os.path.join(REPO, path)
        if argv[1] == "--write":
            with open(full, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(text)
            continue
        try:
            with open(full, encoding="utf-8", newline="") as handle:
                committed = handle.read()
        except OSError:
            committed = None
        if committed != text:
            print(f"generate: {path} differs from the regenerated output", file=sys.stderr)
            status = 1
    return status


if __name__ == "__main__":
    sys.exit(main(sys.argv))
