def inverse_normal_inputs(rng):
    points = []

    def add(p):
        tail = min(D(p), 1 - D(p))
        if tail >= D("0.075"):
            domain = 0
        elif tail >= D(-25).exp():
            domain = 1
        else:
            domain = 2
        points.append((p, domain))

    # Wichura's design, uniform on a logit scale, wider: logit p in [-745, 37].
    for _ in range(2400):
        logit = D(-745) + D(782) * uniform(rng)
        p = to_double(1 / (1 + (-logit).exp()))
        if 0.0 < p < 1.0:
            add(p)
    for _ in range(1600):
        add(to_double(D("0.075") + D("0.85") * uniform(rng)))
    # The middle region, log-uniform in the tail, either side: the logit design puts few points here.
    for _ in range(1200):
        tail = (D(-25) + (D(-25).copy_abs() + D("0.075").ln()) * uniform(rng)).exp()
        add(to_double(tail) if rng.getrandbits(1) else to_double(1 - tail))
    # The philox grid, (k + 1/2) 2^-52, the GBM working domain, both ends.
    for _ in range(600):
        k = rng.getrandbits(52)
        add(to_double((k + D("0.5")) / D(2**52)))
    for k in list(range(0, 40)) + [2**52 - 1 - j for j in range(40)]:
        add(to_double((k + D("0.5")) / D(2**52)))
    # Branch joins: |q| = 0.425 and r = 5.
    for anchor in (0.075, 0.925, to_double(D(-25).exp()), to_double(1 - D(-25).exp())):
        for p in ulp_neighbours(anchor, 8):
            add(p)
    # Where the Phase 2 test against an erfc reference saw its largest errors, one per region.
    for p in PHASE2_WORST:
        for q in ulp_neighbours(p, 2):
            add(q)
    for p in SURVEY_WORST:
        add(p)
    for p in (5e-324, 2.0**-1074 * 3, 2.0**-1022, 1e-300, 1e-100, 1e-20, 2.0**-53, 0.25, 0.5 + 2.0**-53,
              0.75, 1 - 2.0**-53):
        add(p)
    return points


