#!/usr/bin/env python3
"""Polynomial fits and reference values for the kernels in src/math/.

    python3 -I tools/math_reference/generate.py --write | --check
    python3 -I tools/math_reference/generate.py --survey <count> <file under build/>

Standard library only. Every value comes from the decimal module, whose exp, ln and sqrt are
correctly rounded at the working precision, and from exact conversions between decimal and
binary: Decimal(float) is exact, and float(Decimal) rounds correctly through Python's own string
conversion. Nothing here calls the host's libm, so the output is the same on every host.

Outputs, each between generated-block markers or in a file of its own:
  src/math/common.hpp                 ln2 split for Cody-Waite reduction, 1/ln2, sqrt 2
  src/math/exp.hpp, src/math/log.hpp  the minimax coefficients, from a Remez exchange run here
  tests/math/reference_values.inc     inputs with exact references as hi + lo double pairs

--write rewrites them. --check regenerates them and exits 1 if any differs by a byte, so the
committed coefficients and table cannot drift from this script. --survey writes count random p
per inverse-normal region with exact values, for a wider look at AS241 than the committed table
gives, read by the aadp_math_survey tool. Its output is not committed.

Self-checks run first in both modes and exit 1 on failure: pi two ways; erfc by series and by
continued fraction where both converge; the continued fraction at two depths; every Remez fit
levelled, and every fit after rounding its coefficients to double within its stated limit;
every inverse normal Newton iteration converged.

Exit codes: 0 pass, 1 a self-check failed or --check found a difference, 2 usage.
"""

