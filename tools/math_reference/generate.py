def exp_inputs(rng, ln2):
    points = []

    def add(domain, x):
        points.append((x, domain))

    for _ in range(800):
        add(0, to_double(D("-745.2") + D("1455") * uniform(rng)))
    for _ in range(500):
        add(1, to_double(-1 + 2 * uniform(rng)))
    for _ in range(400):
        add(2, to_double(-20 + 40 * uniform(rng)))
    ks = sorted(set(list(range(-1075, 1025, 11)) + [-1075, -1, 0, 1, 1023, 1024]))
    for k in ks:
        centre = to_double((k + D("0.5")) * ln2)
        for x in ulp_neighbours(centre, 1):
            if D(-745) <= D(x) <= D("709.78"):
                add(3, x)
        if k != 0:
            for x in ulp_neighbours(to_double(k * ln2), 1):
                if D(-745) <= D(x) <= D("709.78"):
                    add(4, x)
    overflow = to_double(D(2).ln() * 1024)  # ln(2^1024): exp overflows just below it
    underflow = to_double(D(2).ln() * -1075)  # exp rounds to 0 at or below about this
    subnormal = to_double(D(2).ln() * -1022)  # results below are subnormal
    for anchor in (overflow, underflow, subnormal, to_double(D(2).ln() * -1074)):
        for x in ulp_neighbours(anchor, 4):
            add(5, x)
    for x in (709.78, 709.7827128933839, 709.78271289338397, -708.4, -730.0, -744.0, -745.0):
        add(5, x)
    for e in range(-1074, -10, 37):
        add(5, 2.0**e)
        add(5, -(2.0**e))
    return points


