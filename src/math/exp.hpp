// exp for double, the pricer's own, so results do not depend on the host's libm.
//
// Method: Cody and Waite, Software Manual for the Elementary Functions, Prentice-Hall 1980, ch. 6.
// x = k ln2 + r with |r| <= ln2/2, ln2 split in two so that k ln2_hi is exact, and
// exp(x) = 2^k exp(r). Then exp(r) = 1 + r + r^2 P(r), P a minimax fit of (exp(r) - 1 - r) / r^2
// from tools/math_reference/generate.py, which also checks it. The rounding errors of the
// reduction and of 1 + r are carried exactly with Fast2Sum (Dekker, Numer. Math. 18, 1971), so the
// only large rounding is the last addition. 2^k is applied as two exact powers of two, so 2^1024
// needs no special case and a subnormal result is rounded once.
//
// Accuracy target, stated before measuring: below 1 ULP of the exact result for every x, so the
// result is one of the two doubles either side of exp(x). Budget where it is tightest, exp(r)
// just above 1/sqrt2: 0.5 ULP for the last addition, about 0.25 for r^2 P(r) and its rounding,
// under 0.01 for the fit, so about 0.8, and 1 leaves a margin. A subnormal result adds one
// rounding to the subnormal grid, at most 0.5 of its spacing, while the earlier error shrinks to a
// fraction of it. Measured in tests/math/exp_log_test.cpp.
//
// Edge contract: NaN gives the canonical quiet NaN. +inf, and any x whose exp rounds above
// DBL_MAX (x > 709.782712893384), give +inf. -inf, and any x whose exp is below half the smallest
// subnormal (x < -745.1332191019412), give +0. Subnormal results are gradual, never flushed. +0,
// -0 and subnormal x give exactly 1.
//
// No FMA. The argument is clamped to [-746, 710], where exp is already 0 or inf, and NaN is
// replaced by 0, so the main path never sees a value that would need a branch.
#ifndef AADP_MATH_EXP_HPP_
#define AADP_MATH_EXP_HPP_

#include <array>
#include <bit>
#include <cstdint>

#include "math/common.hpp"

namespace aadp::math {

namespace exp_detail {

inline constexpr double kMinArgument = -746.0;
inline constexpr double kMaxArgument = 710.0;

// clang-format off
// BEGIN GENERATED by tools/math_reference/generate.py. Do not edit.
// Remez minimax in relative error, degree 10 in r on [-0.34658, 0.34658].
// Levelled error 2.715e-18; with the coefficients rounded to double, 6.142e-18.
inline constexpr std::array<double, 11> kExpPoly = {
    0x1.0000000000000p-1,  // 0.5
    0x1.5555555555557p-3,  // 0.1666666666666667
    0x1.555555555554ep-5,  // 0.041666666666666616
    0x1.11111111100eep-7,  // 0.008333333333326167
    0x1.6c16c16c1a076p-10,  // 0.0013888888888917961
    0x1.a01a01abdf558p-13,  // 0.00019841269874724498
    0x1.a01a019061b86p-16,  // 2.4801587245739113e-05
    0x1.71de024a34c5ap-19,  // 2.7557255509541092e-06
    0x1.27e510db143c2p-22,  // 2.7557349619339546e-07
    0x1.af4dbad87cff4p-26,  // 2.5105175578994213e-08
    0x1.1f19f45ea0e84p-29,  // 2.0889375084867933e-09
};
// END GENERATED
// clang-format on

}  // namespace exp_detail

inline double exp(double x) {
  using detail::Horner;
  using detail::kShifter;
  using exp_detail::kExpPoly;
  const bool is_nan = x != x;
  double xc = x < exp_detail::kMinArgument ? exp_detail::kMinArgument : x;
  xc = xc > exp_detail::kMaxArgument ? exp_detail::kMaxArgument : xc;
  xc = is_nan ? 0.0 : xc;

  // k = round(x / ln2), as a double and as an integer from the low bits of the shifted sum.
  const double shifted = xc * detail::kInvLn2 + kShifter;
  const double kd = shifted - kShifter;
  const std::int64_t k =
      std::bit_cast<std::int64_t>(shifted) - std::bit_cast<std::int64_t>(kShifter);

  // r + r_err = x - k ln2: kd * kLn2Hi is exact, and so is the subtraction from x (Sterbenz).
  const double r_hi = xc - kd * detail::kLn2Hi;
  const double p = kd * detail::kLn2Lo;
  const double r = r_hi - p;
  const double r_err = (r_hi - r) - p;

  // exp(r + r_err) = s + s_err + r^2 P(r) + r_err exp(r), where s + s_err = 1 + r exactly.
  const double s = 1.0 + r;
  const double s_err = (1.0 - s) + r;
  const double w = r * r * Horner(kExpPoly, r) + r_err * s;
  const double m = s + (s_err + w);

  // 2^k as 2^k1 * 2^k2, both normal for k in [-1076, 1024], so m * 2^k1 is exact and only the
  // last product rounds. Any split with both halves normal gives the same bits.
  const std::int64_t k1 = k / 2;
  const std::int64_t k2 = k - k1;
  const auto scale1 =
      std::bit_cast<double>(static_cast<std::uint64_t>(k1 + detail::kExponentBias) << 52U);
  const auto scale2 =
      std::bit_cast<double>(static_cast<std::uint64_t>(k2 + detail::kExponentBias) << 52U);
  const double result = m * scale1 * scale2;
  return is_nan ? detail::kNaN : result;
}

}  // namespace aadp::math

#endif  // AADP_MATH_EXP_HPP_
