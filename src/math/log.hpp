// Natural log for double, the pricer's own, so results do not depend on the host's libm.
//
// Method: Cody and Waite, Software Manual for the Elementary Functions, Prentice-Hall 1980, ch. 5.
// x = 2^e m with m in [sqrt(1/2), sqrt 2), read from the exponent and mantissa fields, and
// log x = e ln2 + log(1 + f), f = m - 1, exact. With s = f / (2 + f), log(1 + f) = 2 atanh(s),
// rearranged so that f itself is never rounded:
//   log(1 + f) = f - f^2/2 + s (f^2/2 + z P(z)),   z = s^2,
// which follows from 2s = f - s f, with P a minimax fit of (2 atanh(s) / s - 2) / z from
// tools/math_reference/generate.py, which also checks it. e ln2_hi is exact, and its sum with f
// is kept exactly with TwoSum (Knuth, TAOCP vol. 2, 4.2.2), so the last addition is the only
// large rounding. Subnormal x is scaled by 2^54 first.
//
// Accuracy target, stated before measuring: below 1 ULP of the exact result for every x > 0.
// Budget where it is tightest, e = 0 and f near sqrt 2 - 1: 0.5 ULP for the last addition, about
// 0.4 for the correction term, whose s carries two roundings, and under 0.01 for the fit, so about
// 0.9. Elsewhere e ln2 or the exact f dominates and the error is close to 0.5. Measured in
// tests/math/exp_log_test.cpp.
//
// Edge contract: log(+0) = log(-0) = -inf. Any x < 0, -inf and NaN give the canonical quiet
// NaN. log(+inf) = +inf. log(1) = +0 exactly. Subnormal x is handled at full accuracy.
//
// One division, no FMA, no branch on x: invalid arguments are replaced by 1 before the main path
// and the edges are selects at the end.
#ifndef AADP_MATH_LOG_HPP_
#define AADP_MATH_LOG_HPP_

#include <array>
#include <bit>
#include <cstdint>

#include "math/common.hpp"

namespace aadp::math {

namespace log_detail {

inline constexpr double kSmallestNormal = 0x1p-1022;
inline constexpr double kSubnormalScale = 0x1p54;
inline constexpr std::int64_t kSubnormalShift = 54;

// clang-format off
// BEGIN GENERATED by tools/math_reference/generate.py. Do not edit.
// Remez minimax in relative error, degree 7 in z on [0, 0.02944].
// Levelled error 3.042e-18; with the coefficients rounded to double, 5.551e-17.
inline constexpr std::array<double, 8> kLogPoly = {
    0x1.5555555555555p-1,  // 0.6666666666666666
    0x1.9999999999a38p-2,  // 0.4000000000000088
    0x1.2492492476b5cp-2,  // 0.2857142857080157
    0x1.c71c72017e710p-3,  // 0.22222222392138535
    0x1.745cf8f61bdd5p-3,  // 0.1818179559809169
    0x1.3b1c3838546bep-3,  // 0.15386241838364428
    0x1.0fbe4dadbd262p-3,  // 0.13268719374140675
    0x1.0c0665b00771cp-3,  // 0.13087157672355765
};
// END GENERATED
// clang-format on

}  // namespace log_detail

inline double log(double x) {
  using detail::Horner;
  using detail::kInf;
  using log_detail::kLogPoly;
  const bool finite_positive = x > 0.0 && x < kInf;
  const double xv = finite_positive ? x : 1.0;
  const bool subnormal = xv < log_detail::kSmallestNormal;
  const double xs = subnormal ? xv * log_detail::kSubnormalScale : xv;

  // xs = 2^e0 m0 with m0 in [1, 2), then m in [sqrt(1/2), sqrt 2).
  const auto bits = std::bit_cast<std::uint64_t>(xs);
  const auto m0 = std::bit_cast<double>((bits & detail::kMantissaMask) | detail::kExponentOfOne);
  const bool high = m0 >= detail::kSqrt2;
  const double m = high ? 0.5 * m0 : m0;
  const std::int64_t e_int = static_cast<std::int64_t>(bits >> 52U) - detail::kExponentBias -
                             (subnormal ? log_detail::kSubnormalShift : 0) + (high ? 1 : 0);
  const auto e = static_cast<double>(e_int);

  const double f = m - 1.0;
  const double s = f / (2.0 + f);
  const double z = s * s;
  const double half_f_squared = 0.5 * f * f;
  const double correction = s * (half_f_squared + z * Horner(kLogPoly, z)) - half_f_squared;

  // e ln2_hi + f with its rounding error kept, then the small terms, then one last rounding.
  const double a = e * detail::kLn2Hi;
  const double sum = a + f;
  const double b = sum - a;
  const double sum_err = (a - (sum - b)) + (f - b);
  double result = sum + (sum_err + (correction + e * detail::kLn2Lo));

  result = x == 0.0 ? -kInf : result;
  result = x == kInf ? kInf : result;
  return (x < 0.0 || x != x) ? detail::kNaN : result;
}

}  // namespace aadp::math

#endif  // AADP_MATH_LOG_HPP_
